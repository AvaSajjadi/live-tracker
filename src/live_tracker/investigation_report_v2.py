def _t_descriptive(c):
    g = c["grounding"]
    sessions = g["contributing_sessions"]
    if not isinstance(sessions, (list, tuple)) or len(sessions) != g["n_sessions_paired"]:
        _fail("the contributing sessions do not match the paired-session count")
    src = g.get("source")
    if src is None:                                    # claims/2.0: unchanged
        text = (f"Across the {_int(len(sessions))} contributing paired sessions ({_ids(sessions, 'session')}), the "
                "median of per-session differences (pre-event minus baseline) in "
                f"{_tok(g['feature'])} was {_number(g['value'])} {_unit_text(g['unit'])} "
                f"({_one_of(g['direction'], ('positive', 'negative', 'zero'), 'direction')}). Descriptive only: no "
                "interval or test; not a causal reading; it describes these sessions, not the whole authorized split.")
    else:
        label, precede = _onset_words(src)
        text = (f"Across the {_int(len(sessions))} contributing paired sessions ({_ids(sessions, 'session')}), for "
                f"{_source_phrase(src)}, the median of per-session differences ({label} minus baseline) in "
                f"{_tok(g['feature'])} was {_number(g['value'])} {_unit_text(g['unit'])} "
                f"({_one_of(g['direction'], ('positive', 'negative', 'zero'), 'direction')}). The windows precede "
                f"{precede}, not necessarily the behavior. Descriptive only: no interval or test; not a causal "
                "reading; not a measure of model accuracy; it describes these sessions, not the whole authorized "
                "split.")
    cross = _one_of(g["cross_snapshot_status"], ("verified", "partially_verified", "not_verified", "not_applicable"),
                    "cross-snapshot status")
    if cross != "verified":
        text += f" Cross-snapshot agreement: {cross}."
    status = _one_of(g["coverage_status"], ("complete", "partial"), "coverage status")
    if status == "partial":
        cov = g["coverage"]
        reason = _coverage_reason(cov["reason"])
        text += (f" Coverage: partial: {_int(cov['searched'])} of {_eligible(cov['eligible'])} eligible sessions were "
                 f"searched for {_tok(cov['behavior'])} ({_definition({**cov['definition'], 'behavior': cov['behavior']})}"
                 f"; not searched: {_not_searched(cov['not_searched'])}"
                 + (f"; reason: {reason}" if reason else "")
                 + "); the unsearched sessions are not described.")
    return text


def _t_coverage(c):
    g, aspect = c["grounding"], c["params"]["aspect"]
    if aspect == "primary_comparison":
        status = _one_of(g["status"], ("complete", "partial", "unknown"), "coverage status")
        contributing = f"{_int(len(g['contributing']))} contributing sessions ({_ids(g['contributing'], 'session')})"
        reason = _coverage_reason(g["reason"])
        if g["query_group"] is None:
            return f"Coverage of the primary comparison: {status}: {reason}; {contributing}."
        q = g["query_group"]
        excluded = "; ".join(f"{_tok(x['session'])} ({_one_of(x['reason'], _EXCLUDED_REASONS, 'exclusion')})"
                             for x in g["excluded"]) or "none"
        return (f"Coverage of the primary comparison: {status}: {_int(len(q['searched']))} of "
                f"{_eligible(q['eligible_count'])} eligible sessions were searched for {_tok(q['behavior'])} "
                f"({_definition(q)}; eligibility: {_basis(q['basis'])}; not searched: "
                f"{_not_searched(q['not_searched'])}); {contributing}; searched sessions with {_tok(q['behavior'])} "
                f"not contributing: {excluded}." + (f" Reason: {reason}." if reason else ""))
    if aspect == "query_group":
        return _group_sentence(g, f"Query coverage ({_eid(c['evidence_ids'][0])})")
    if aspect == "truncated_query":
        return (f"The query {_eid(c['evidence_ids'][0])} was truncated: {_int(g['returned'])} of "
                f"{_int(g['total'])} bouts were returned.")
    if aspect == "window_exclusions":
        windows = ", ".join(f"{_one_of(k, ('pre_event', 'baseline'), 'window kind')} {_int(n)}"
                            for k, n in g["excluded_windows"].items())
        reasons = ", ".join(f"{_tok(k, 'reason')} {_int(n)}" for k, n in g["reason_counts"].items())
        return (f"Measured ({_eid(c['evidence_ids'][0])}): excluded windows: {windows}; exclusion reasons (counts "
                f"can overlap): {reasons}.")
    return f"Sessions with pre-event windows but no eligible baseline window: {_ids(g['sessions'], 'session')}."


def _t_tracking(c):
    return "Measured: " + "; ".join(_tracking_item(t) for t in c["grounding"]["items"]) + "."


def _t_operational(c):
    g, kind = c["grounding"], c["params"]["kind"]
    if kind == "quality_never_called":
        return "Operational: check_tracking_quality was never called in this investigation."
    if kind == "quality_check_refused":
        return ("Operational: every check_tracking_quality call in this investigation was refused by the "
                f"investigation loop (refusals: {_ids(g['refusals'], 'refusal')}); tracking quality was not "
                "assessed per window.")
    if kind == "quality_check_failed":
        return (f"Operational: check_tracking_quality returned an error ({_eid(c['evidence_ids'][0])}; error codes: "
                f"{_ids(g['error_codes'], 'error code')}); it assessed no window.")
    return (f"Operational: the model ({_ids(g['model_ids'], 'model id')}) requested {_int(g['tool_calls_chosen'])} "
            "tool calls in its turns (finish and refused requests included); the sequence of calls was not fixed in "
            "advance.")


def _labels(counts):
    if set(counts) != set(LABEL_ORDER):
        _fail("label counts are not the four CalMS21 labels")
    return ", ".join(f"{x} {_int(counts[x])}" for x in LABEL_ORDER)


def _t_confounder(c):
    g = c["grounding"]
    before = "the event" if g["behavior"] is None else _tok(g["behavior"], "behavior")
    return (f"Potential confounder (measured in {_eid(c['evidence_ids'][0])}): pre-event label frames "
            f"{_labels(g['label_frames_pre'])}; baseline {_labels(g['label_frames_baseline'])}. The difference may "
            f"reflect investigation versus other behaviour rather than time before {before}; this is not "
            "established.")


