@dataclass(frozen=True)
class RenderedReport:
    """A rendered report with its format and verification label. For legacy/1,
    `doc` and `markdown` are the legacy renderer's output, byte for byte; the
    quarantine of their model-authored prose is described here, outside them."""
    format: str                  # "legacy/1" or "findings/2"
    verification: str            # legacy_verified | publishable | record_only | diagnostic
    authorization: str           # rechecked | not_rechecked
    doc: Any
    markdown: str
    quarantine: Any              # legacy/1 only: the model-authored prose and its label; None for findings/2
    notice: str                  # a separate one-paragraph notice (never inserted into the legacy bytes)


def _legacy(report, policy):
    doc = ir.build_report(report, policy=policy)
    markdown = ir.render_markdown(doc)
    model_limitations = [l["text"] for l in report.limitations if l["source"] == "model"]
    quarantine = {
        "label": LEGACY_PROSE_LABEL,
        "fields": {"interpretations": len(report.interpretations), "next_steps": len(report.next_steps),
                   "model_limitations": len(model_limitations)},
        "sections": ["Interpretations", "Next steps", "Limitations (model)"],
        "in_executive_summary": False,
        "upgraded_to_findings_v2": False,
        "verified_layers": "L0 content consistency, L1 schema, execution trace, L3 cross-snapshot and coverage "
                           "(legacy checks); L4 claim grounding does not exist for legacy reports",
    }
    authorization = "rechecked" if policy is not None else "not_rechecked"
    notice = (f"Format legacy/1, legacy_verified (authorization {authorization}). Interpretations, next steps and "
              f"model limitations are {LEGACY_PROSE_LABEL}: they are not evidence-verified findings and were not "
              "converted to findings/2 claims.")
    return RenderedReport(format=ctx.LEGACY_FORMAT, verification="legacy_verified", authorization=authorization,
                          doc=doc, markdown=markdown, quarantine=quarantine, notice=notice)


def render_payload(payload, *, policy=None):
    """Render a Stage 6 report (InvestigationReport or JSON payload) by its
    format: legacy/1 through the unchanged legacy renderer (legacy_verified,
    prose quarantined), findings/2 through the v2 renderer. Unknown or mixed
    formats raise ReportIntegrityError; nothing is upgraded between formats."""
    try:
        return _dispatch(payload, policy)
    except ReportIntegrityError:
        raise
    except Exception as exc:
        raise ReportIntegrityError([f"malformed report ({type(exc).__name__})"]) from None


def _dispatch(payload, policy):
    if isinstance(payload, ia.InvestigationReportV2):
        payload = payload.to_json()
    if isinstance(payload, ia.InvestigationReport):
        if ir.report_format(payload) != ctx.LEGACY_FORMAT:
            raise ReportIntegrityError(["an InvestigationReport object is legacy/1 only"])
        return _legacy(payload, policy)
    fmt = ir.report_format(payload)
    if fmt == ctx.LEGACY_FORMAT:
        return _legacy(ir.load_report(payload), policy)
    doc, markdown = render_v2(payload, policy=policy)
    publication = doc["status"]["publication"]
    notice = (f"Format findings/2 (registry {doc['format']['registry_version']}), {publication}: statements are "
              "generated from re-validated structured claims by fixed templates; no model prose is rendered.")
    return RenderedReport(format=ctx.V2_FORMAT, verification=publication,
                          authorization=doc["verification"]["authorization"], doc=doc, markdown=markdown,
                          quarantine=None, notice=notice)
