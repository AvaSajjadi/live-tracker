def _load(payload):
    """A deep copy of a findings/2 payload after strict format and shape checks."""
    if isinstance(payload, ia.InvestigationReport):
        raise ReportIntegrityError(["a legacy InvestigationReport is never rendered as findings/2 (legacy reports "
                                    "are not upgraded)"])
    if isinstance(payload, ia.InvestigationReportV2):
        payload = payload.to_json()
    fmt = ir.report_format(payload)            # mixed / unknown / malformed markers refuse here
    if fmt != ctx.V2_FORMAT:
        raise ReportIntegrityError(["a legacy/1 payload is never rendered as findings/2 (legacy reports are not "
                                    "upgraded); use render_payload"])
    keys = set(payload)
    legacy = sorted(keys & LEGACY_ONLY_FIELDS)
    if legacy:
        raise ReportIntegrityError([f"mixed payload: a findings/2 report carries legacy fields {legacy}"])
    if keys != V2_REPORT_FIELDS:
        raise ReportIntegrityError([f"findings/2 payload fields: unknown {sorted(keys - V2_REPORT_FIELDS)}, missing "
                                    f"{sorted(V2_REPORT_FIELDS - keys)}"])
    data = copy.deepcopy(dict(payload))
    types_ok = (isinstance(data["question"], str) and type(data["finished"]) is bool and
                isinstance(data["stopping_reason"], str) and isinstance(data["evidence"], list) and
                isinstance(data["trace"], list) and isinstance(data["usage"], dict) and
                isinstance(data["fingerprint"], str) and isinstance(data["claims"], list) and
                isinstance(data["observations"], list) and isinstance(data["next_investigations"], list))
    if not types_ok:
        raise ReportIntegrityError(["findings/2 payload: malformed field types"])
    for t in data["trace"]:
        # only the accepted finish carries the report's findings; a refused attempt is recorded history (never
        # rendered: the trace's arguments are not part of the document)
        args = t.get("arguments") if isinstance(t, dict) and t.get("kind") == "finish" and \
            t.get("outcome") == "accepted" else None
        if isinstance(args, dict) and any(args.get(k) for k in LEGACY_FINISH_PROSE):
            raise ReportIntegrityError(["mixed payload: the trace's finish carries legacy model-authored prose"])
    return data


def _revalidate(data, policy):
    """The FindingsV2 of a payload re-validated from its evidence (L0-L4), then the fingerprint compared."""
    proposal = {k: data[k] for k in cl.PROPOSAL_KEYS}
    if data["finding"] == "incomplete" or not data["finished"]:
        if data["finding"] != "incomplete" or data["finished"]:
            raise ReportIntegrityError(["an unfinished run has the finding 'incomplete', and only an unfinished run "
                                        "has it"])
        if data["primary_evidence_id"] is not None or data["claims"] or data["observations"] or \
                data["next_investigations"]:
            raise ReportIntegrityError(["an incomplete run never acquires a primary, claims, observations or next "
                                        "investigations"])
        result = cl.incomplete_findings(evidence=data["evidence"], trace=data["trace"], policy=policy,
                                        stopping_reason=data["stopping_reason"],
                                        registry_version=data["registry_version"])
    else:
        result = cl.validate_findings(proposal, evidence=data["evidence"], trace=data["trace"], policy=policy,
                                      mode="complete", stopping_reason=data["stopping_reason"], finished=True,
                                      registry_version=data["registry_version"])
    if not result.accepted:
        raise ReportIntegrityError([f"claims: {p}" for p in result.problems] or ["claims: refused"])
    if data["finished"]:                             # M3: the accepted finish carried exactly these findings
        bound = cl.finish_arguments_problems(proposal, data["trace"])
        if bound:
            raise ReportIntegrityError([f"execution: {p}" for p in bound])
    if result.fingerprint != data["fingerprint"]:    # compared only for content that passed re-validation
        raise ReportIntegrityError([f"fingerprint mismatch: recorded {data['fingerprint'][:80]!r}, recomputed "
                                    f"{result.fingerprint!r}"])
    context, problems = ctx.context_from_evidence(
        data["evidence"], policy=policy, primary_evidence_id=data["primary_evidence_id"], trace=data["trace"],
        mode="complete", stopping_reason=data["stopping_reason"], finished=data["finished"])
    if context is None:                              # unreachable after acceptance; fail closed regardless
        raise ReportIntegrityError(problems)
    return result, context


def _step(t):
    keep = ("step", "kind", "elapsed_s", "tool", "outcome", "evidence_id", "refused", "stopping_reason", "model",
            "input_tokens", "output_tokens", "problem")
    out = {k: copy.deepcopy(t[k]) for k in keep if k in t}
    if t.get("text"):
        out["model_reasoning_unverified"] = t["text"]       # JSON only; never rendered
    return out


def build_report_v2(payload, *, policy=None):
    """The verified findings/2 report document (schema 0.2); raises ReportIntegrityError."""
    try:
        data = _load(payload)
        result, context = _revalidate(data, policy)
        return _document(data, result, context, policy)
    except ReportIntegrityError:
        raise
    except Exception as exc:                          # anything malformed is a refusal, never another exception
        raise ReportIntegrityError([f"malformed findings/2 report ({type(exc).__name__})"]) from None


def _document(data, result, context, policy):
    snaps = context.snapshot_dicts()
    finding = result.finding
    claims = []
    for i, c in enumerate(ctx.thaw(result.claims)):
        c = {"index": i, **c}
        c.update(section=SECTION[c["type"]], category=_category(c), limiting=_limiting(c, finding))
        c["sentence"] = TEMPLATES[c["type"]](c)
        claims.append(c)
    observations = []
    for o in ctx.thaw(result.observations):
        snap = snaps[o["evidence_id"]]
        unit = ir._unit_of(snap, o["field"])
        observations.append({**o, "tool": snap["tool"], "unit": unit,
                             "value_rendered": _observation_value(o["value"])})
    nxt = [{**n, "sentence": _next_sentence(n, len(claims))} for n in ctx.thaw(result.next_investigations)]
    execution = context.execution
    doc = {
        "schema": REPORT_SCHEMA_V2,
        "format": {"findings_format": result.findings_format, "registry_version": result.registry_version,
                   "grid_version": result.grid_version, "report_schema": REPORT_SCHEMA_V2,
                   "fingerprint_version": ctx.FINGERPRINT_VERSION},
        "status": {"publication": _publication(result),
                   "finding": finding, "finding_label": FINDING_LABEL[finding], "finished": data["finished"],
                   "stopping_reason": data["stopping_reason"], "primary_evidence_id": result.primary_evidence_id,
                   "accepted_direction": result.accepted_direction},
        "verification": {
            "content_consistency": "consistent: every evidence_id is the unkeyed sha256 of its tool, request and "
                                   "result (content consistency, not authentic tool origin)",
            "schema": "checked: every snapshot is a well-formed contract result of its request",
            "authorization": result.authorization, "policy_digest": context.authorization.policy_digest,
            "execution": {"status": execution.status, "accepted_finish": execution.accepted_finish,
                          "tool_calls": execution.tool_calls, "stopping_reason": execution.stopping_reason},
            "cross_snapshot": ctx.thaw(context.cross_snapshot),
            "claim_grounding": "re-validated: every claim and observation against the rebuilt context",
            "fingerprint": {"recorded": data["fingerprint"], "recomputed": result.fingerprint, "match": True},
            "interpretation": "descriptive (not verified by software)",
            "n_evidence": len(snaps)},
        "question": {"text": data["question"], "source": "operator-supplied research question (not evidence)"},
        "claims": claims,
        "observations": observations,
        "next_investigations": nxt,
        "recorded": {"coverage": ctx.thaw(context.coverage), "tracking": ctx.thaw(context.tracking)},
        "data_provenance": _data_provenance(snaps),
        "statistical_policy": DESCRIPTIVE_POLICY,
        "unit_of_analysis": UNIT_OF_ANALYSIS,
        "association_only": True,            # Contract v1 shared surface item 4: never a causal finding
        "trace": {"stopping_reason": data["stopping_reason"], "usage": copy.deepcopy(data["usage"]),
                  "steps": [_step(t) for t in data["trace"]],
                  "note": "model_reasoning_unverified is the model's own text, recorded and never rendered"},
        "evidence_appendix": [{"evidence_id": eid, "tool": e["tool"], "status": e["status"]}
                              for eid, e in snaps.items()],
        # the canonical input: a saved document is re-rendered only by rebuilding it from this (see verify_saved_v2)
        "canonical": copy.deepcopy(data),
    }
    if result.source_context is not None:            # claims/2.1 only (claims/2.0 documents are unchanged)
        doc["source"] = _source_section(ctx.thaw(result.source_context))
    doc["recorded"]["coverage_sentences"] = _recorded_coverage(doc["recorded"]["coverage"])
    doc["recorded"]["tracking_sentences"] = [_tracking_item(t) + "." for t in doc["recorded"]["tracking"]]
    doc["executive_summary"] = _executive_summary(doc)
    return doc


def _publication(result):
    """publishable: rechecked under a policy, finished, and the registry is
    authorized for publication; not_authorized: rechecked and finished, but the
    registry (claims/2.1, prediction evidence) is not authorized yet;
    record_only: rechecked, incomplete; diagnostic: no policy."""
    if result.finding == "incomplete":
        return "record_only" if result.authorization == "rechecked" else "diagnostic"
    if result.publishable:
        return "publishable"
    if result.authorization == "rechecked" and not cl.PUBLICATION_AUTHORIZED[result.registry_version]:
        return "not_authorized"
    return "diagnostic"


def _data_provenance(snaps):
    kinds = sorted({d["kind"] for e in snaps.values() for d in e["result"]["provenance"]["data"]})
    splits = sorted({x["provenance"]["split"] for e in snaps.values() if e["tool"] == "query_events"
                     and e["result"]["measurements"] for x in e["result"]["measurements"]["episodes"]
                     if "split" in x["provenance"]})
    return {"data_kinds": kinds, "synthetic": None if not kinds else "synthetic_fixture" in kinds, "splits": splits}


