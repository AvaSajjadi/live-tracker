class TemplateError(ReportIntegrityError):
    """A value cannot be rendered by a fixed template (outside its grammar)."""


def _fail(what):
    raise TemplateError([f"template: {what}"])


# ======================================================================
# value guards: everything a template interpolates passes one of these
# ======================================================================

def _tok(v, what="identifier"):
    if not isinstance(v, str) or not _TOKEN.fullmatch(v):
        _fail(f"{what} {str(v)[:40]!r} is outside the identifier grammar")
    return v


def _eid(v):
    if not isinstance(v, str) or not _EID.fullmatch(v):
        _fail(f"evidence id {str(v)[:40]!r} is outside the evidence-id grammar")
    return v


def _int(v, what="count"):
    if type(v) is not int or v < 0:
        _fail(f"{what} {str(v)[:40]!r} is not a non-negative integer")
    return str(v)


def _number(v, what="value"):
    if type(v) not in (int, float) or not math.isfinite(v):
        _fail(f"{what} {str(v)[:40]!r} is not a finite number")
    return ctx._fmt(v)


def _unit_text(u):
    if u is None:
        return "(unit not recorded)"
    if u not in KNOWN_UNITS:
        _fail(f"unit {str(u)[:40]!r} is not a known unit")
    return u


def _ids(values, what="identifier", check=None):
    check = check or (lambda x: _tok(x, what))
    if not isinstance(values, (list, tuple)):
        _fail(f"{what} list is not a list")
    return ", ".join(check(x) for x in values) or "none"


def _one_of(v, allowed, what):
    if v not in allowed:
        _fail(f"{what} {str(v)[:40]!r} is not one of {list(allowed)}")
    return v


def _coverage_reason(reason):
    """A primary-coverage reason as fixed text; identity details stay in the JSON record."""
    if reason is None:
        return None
    if not isinstance(reason, str):
        _fail("coverage reason is not text")
    parts, m = [], _PARTIAL_CACHE.fullmatch(reason)
    head = reason
    if m:
        head = m.group(1)
        tail = f"partial cache coverage recorded by {m.group(2)}"
    if head is not None:
        if head in _FIXED_REASONS or _NO_GROUP_REASON.fullmatch(head):
            parts.append(head)
        elif head.startswith(_IDENTITY_REASON):
            parts.append("the comparison's data identity is not established along its provenance chain "
                         "(details in the JSON coverage record)")
        else:
            _fail(f"coverage reason {head[:60]!r} is not a known context reason")
    if m:
        parts.append(tail)
    return "; ".join(parts)


def _basis(basis):
    if not isinstance(basis, str):
        _fail("coverage basis is not text")
    head, sep, rest = basis.partition("; the group's queries do not share data identity")
    if not (_BASIS_SPLIT.fullmatch(head) or head in _BASES):
        _fail(f"coverage basis {head[:60]!r} is not a known context basis")
    return head + ("; the group's queries do not share data identity (details in the JSON coverage record)"
                   if sep else "")


def _definition(d):
    gap, low = d["merge_gap_frames"], d["min_duration_frames"]
    return (f"source {_tok(d['source'])}, behavior {_tok(d['behavior'])}, "
            + ("no merge gap" if gap is None else f"merge gap {_int(gap, 'merge gap')} frames") + ", "
            + ("no minimum duration" if low is None else f"minimum duration {_int(low, 'minimum duration')} frames"))


def _eligible(n):
    return "an unknown number of" if n is None else _int(n, "eligible count")


def _not_searched(ids):
    return "not established" if ids is None else _ids(ids, "session")


def _group_sentence(g, lead):
    """One query group's coverage (status always from the context)."""
    text = (f"{lead}: {_one_of(g['status'], ('complete', 'partial', 'unknown'), 'coverage status')}: "
            f"{_int(len(g['searched']))} of {_eligible(g['eligible_count'])} eligible sessions were searched for "
            f"{_tok(g['behavior'])} ({_definition(g)}; eligibility: {_basis(g['basis'])}; not searched: "
            f"{_not_searched(g['not_searched'])}); {_int(len(g['with_behavior']))} searched sessions with "
            f"{_tok(g['behavior'])} (query evidence: {_ids(g['query_evidence_ids'], check=_eid)})")
    if g["truncated"] is True:
        text += "; a query was truncated: not every bout of the searched sessions was returned"
    return text + "."


def _tracking_item(t):
    pattern = _TRACKING_TEXT.get(t["source"])
    if pattern is None or not isinstance(t["text"], str) or not pattern.fullmatch(t["text"]):
        _fail(f"tracking fact {str(t['text'])[:60]!r} is not a known context text")
    where = _eid(t["evidence_id"]) if t["evidence_id"] is not None else "execution history"
    return f"{t['text']} ({where}, {t['source']})"


