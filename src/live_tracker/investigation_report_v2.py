"""EXPERIMENTAL (Investigation mode, Findings v2 checkpoint M2): deterministic
findings/2 report rendering and legacy quarantine (new file). Design:
docs/findings_v2_design.md sections 3.3, 5-10.

    rendered = render_payload(payload, policy=policy)   # dispatch: legacy/1 or findings/2
    doc, markdown = render_v2(payload, policy=policy)   # findings/2 only

A findings/2 payload is structured data only (no prose): the run's evidence
and trace, the finding, the claims / observations / next investigations of
the `claims/2.0` registry, and the content fingerprint (fp/1) recorded when
the findings were frozen. Rendering follows the design's order (3.3): format
dispatch; L0 content consistency, L1 schema, L2 authorization (when a policy
is given) and the execution assessment; the rebuilt context; L4 re-validation
of every claim and observation by the registry (investigation_claims); only
then the fingerprint comparison. Anything that fails refuses the report
(ReportIntegrityError); nothing is rendered from unvalidated content.

Statements are generated by fixed templates (TEMPLATES) from a claim's
type, params, evidence ids and its registry grounding only. A template
interpolates nothing but numbers, identifiers that match a closed grammar
(evidence / session / window ids, features, codes: _TOKEN), units of the
known set (KNOWN_UNITS) and texts the shared context generates from fixed
phrases (checked against closed patterns). Model prose (finish arguments,
model-turn text), the research question's markup, tool notes, methodology
notes and limitation texts are never interpolated: model reasoning stays in
the JSON trace as `model_reasoning_unverified` and is never rendered.
A saved JSON document is untrusted: it carries its canonical payload, and
render_markdown_v2 / verify_saved_v2 rebuild the whole document from that
payload through the M0 context and M1 registry (under the policy given at
render time) and refuse any saved document that is not exactly the rebuild.
Nothing derived (grounding, numbers, sentences, summary, publication status,
authorization, fingerprint status, policy text) is ever taken from it.

Publication status (design Q4): `publishable` only when every result was
re-accepted under an evidence policy (authorization `rechecked`) and the run
finished with a validated finding; without a policy the report is
`diagnostic` and says so; an incomplete run under a policy is `record_only`
(it never acquires a finding).

Legacy quarantine (design section 10): legacy/1 payloads are rendered by the
unchanged Stage 7 renderer (investigation_report: identical JSON and
Markdown bytes), labelled `legacy_verified`, with their model-authored prose
quarantined in metadata outside those bytes. A legacy report is never
upgraded to findings/2, and the findings/2 renderer refuses legacy payloads
and documents; unknown or mixed payloads are refused by both.
"""

