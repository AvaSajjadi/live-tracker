_MD_ESCAPE = re.compile(r"([\\`*_{}\[\]<>|#~!&])")


def _escape(text):
    """Operator text as one inert Markdown line (no markup, links, HTML or line breaks)."""
    return _MD_ESCAPE.sub(r"\\\1", " ".join(str(text).split()))


def _saved_shape(doc):
    """Strict shape of a saved findings/2 document before anything in it is used."""
    if not isinstance(doc, dict) or doc.get("schema") not in KNOWN_SCHEMAS:
        shown = str(doc.get("schema") if isinstance(doc, dict) else type(doc).__name__)[:60]
        raise ReportIntegrityError([f"not a findings/2 report document (schema {shown!r}); legacy documents are "
                                    "rendered only by the legacy renderer"])
    keys = set(doc)
    expected = V2_DOC_FIELDS | ({"source"} if "source" in keys else set())   # the rebuild decides if it belongs
    if keys != expected:
        raise ReportIntegrityError([f"findings/2 document fields: unknown {sorted(keys - expected)[:5]}, missing "
                                    f"{sorted(expected - keys)}"])
    if not isinstance(doc["canonical"], dict):
        raise ReportIntegrityError(["findings/2 document: the canonical payload is missing or malformed"])


def verify_saved_v2(doc, *, policy=None):
    """The document rebuilt from its canonical payload, refusing a saved
    document that is not exactly that rebuild.

    A saved document is untrusted input. Only its `canonical` payload (the
    run's evidence, trace, execution state, structured claims and recorded
    fingerprint) is read; it goes through the same path as a fresh payload
    (format dispatch, M0 L0-L2 / execution / L3 context, M1 L4 re-validation,
    then the fp/1 comparison), and every derived field (grounding, sentences,
    summary, publication status, authorization, verification and policy
    statements) is regenerated under the `policy` given now. Any difference
    from the saved document refuses it; nothing is repaired. Authorization is
    `rechecked` only when a policy is given now, so a publishable document
    rendered without one is refused, never shown as publishable. The
    fingerprint is a consistency check over evidence and claims, not proof of
    origin."""
    try:
        _saved_shape(doc)
        rebuilt = build_report_v2(doc["canonical"], policy=policy)
        if ir.to_json_text(rebuilt) != ir.to_json_text(doc):
            differ = sorted(k for k in set(rebuilt) | set(doc)
                            if k not in rebuilt or k not in doc or ir.to_json_text(rebuilt[k]) != ir.to_json_text(doc[k]))
            hint = ("; authorization and publication status are reconstructed under the policy given now"
                    if {"status", "verification"} & set(differ) else "")
            raise ReportIntegrityError([f"saved document differs from its reconstruction from the canonical "
                                        f"evidence and claims (fields {differ}){hint}"])
        return rebuilt
    except ReportIntegrityError:
        raise
    except Exception as exc:
        raise ReportIntegrityError([f"malformed findings/2 document ({type(exc).__name__})"]) from None


def render_markdown_v2(doc, *, policy=None):
    """Markdown for a saved findings/2 document, rendered only from its
    reconstruction (verify_saved_v2); a tampered document is refused."""
    rebuilt = verify_saved_v2(doc, policy=policy)
    try:
        return _markdown(rebuilt)
    except ReportIntegrityError:
        raise
    except Exception as exc:
        raise ReportIntegrityError([f"malformed findings/2 document ({type(exc).__name__})"]) from None


